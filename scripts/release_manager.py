#!/usr/bin/env python3
"""
ProValuer Commercial - Automated Release Manager
Single Source of Truth: frontend/pubspec.yaml
"""

import os
import sys
import re
import json
import hashlib
import shutil
import subprocess
from datetime import datetime
from pathlib import Path

# Paths
REPO_ROOT = Path(__file__).resolve().parent.parent
PUBSPEC_PATH = REPO_ROOT / "frontend" / "pubspec.yaml"
VERSION_INFO_DART = REPO_ROOT / "frontend" / "lib" / "constants" / "version_info.dart"
TEMPLATE_HTML_PATH = REPO_ROOT / "android" / "distribution" / "index.template.html"
DIST_DIR = REPO_ROOT / "android" / "distribution"
OUTPUT_DIR = REPO_ROOT / "frontend" / "build" / "app" / "outputs"
DEFAULT_APK_PATH = REPO_ROOT / "frontend" / "build" / "app" / "outputs" / "flutter-apk" / "app-production-release.apk"


def get_aapt_path():
    """Finds aapt executable in PATH or standard Android SDK directories."""
    aapt = shutil.which("aapt") or shutil.which("aapt.exe")
    if aapt:
        return aapt

    # Check local Android SDK build-tools on Windows
    local_app_data = os.environ.get("LOCALAPPDATA")
    if local_app_data:
        sdk_build_tools = Path(local_app_data) / "Android" / "Sdk" / "build-tools"
        if sdk_build_tools.exists():
            for version_dir in sorted(sdk_build_tools.iterdir(), reverse=True):
                cand = version_dir / "aapt.exe"
                if cand.exists():
                    return str(cand)

    # Check standard Linux/macOS paths
    android_home = os.environ.get("ANDROID_HOME") or os.environ.get("ANDROID_SDK_ROOT")
    if android_home:
        sdk_build_tools = Path(android_home) / "build-tools"
        if sdk_build_tools.exists():
            for version_dir in sorted(sdk_build_tools.iterdir(), reverse=True):
                cand = version_dir / "aapt"
                if cand.exists():
                    return str(cand)

    return "aapt"


def parse_pubspec_version():
    """Parses single source of truth: frontend/pubspec.yaml"""
    if not PUBSPEC_PATH.exists():
        raise FileNotFoundError(f"pubspec.yaml not found at {PUBSPEC_PATH}")

    content = PUBSPEC_PATH.read_text(encoding="utf-8")
    match = re.search(r"^version:\s*([0-9]+\.[0-9]+\.[0-9]+)\+([0-9]+)", content, re.MULTILINE)
    if not match:
        raise ValueError(f"Could not find valid version: x.y.z+build in {PUBSPEC_PATH}")

    version_name = match.group(1)
    version_code = int(match.group(2))
    return version_name, version_code


def generate_version_info_dart(version_name, version_code, release_date=None):
    """Generates frontend/lib/constants/version_info.dart"""
    if not release_date:
        release_date = datetime.now().strftime("%d-%b-%Y")

    apk_file_name = f"ProValuer-v{version_name}-build-{version_code}.apk"
    apk_url = f"https://app.provaluer.in/download/{apk_file_name}"

    content = f"""// GENERATED FILE - DO NOT MODIFY MANUALLY
// Generated by scripts/release_manager.py from frontend/pubspec.yaml

class VersionInfo {{
  static const String versionName = '{version_name}';
  static const int versionCode = {version_code};
  static const String branch = 'android';
  static const String releaseDate = '{release_date}';
  static const String apkFileName = '{apk_file_name}';
  static const String apkUrl = '{apk_url}';
}}
"""
    VERSION_INFO_DART.parent.mkdir(parents=True, exist_ok=True)
    VERSION_INFO_DART.write_text(content, encoding="utf-8")
    print(f"[release_manager] Updated {VERSION_INFO_DART.relative_to(REPO_ROOT)} -> {version_name}+{version_code}")


def compute_file_hashes(file_path):
    """Computes SHA-256 and SHA-1 hashes of a binary."""
    sha256 = hashlib.sha256()
    sha1 = hashlib.sha1()
    with open(file_path, "rb") as f:
        while chunk := f.read(65536):
            sha256.update(chunk)
            sha1.update(chunk)
    return sha256.hexdigest().upper(), sha1.hexdigest().upper()


def extract_apk_badging(apk_path):
    """Extracts versionName and versionCode from APK using aapt."""
    aapt_cmd = get_aapt_path()
    try:
        res = subprocess.run([aapt_cmd, "dump", "badging", str(apk_path)], capture_output=True, text=True, check=True)
        m_name = re.search(r"versionName='([^']+)'", res.stdout)
        m_code = re.search(r"versionCode='([^']+)'", res.stdout)
        pkg_version_name = m_name.group(1) if m_name else None
        pkg_version_code = int(m_code.group(1)) if m_code else None
        return pkg_version_name, pkg_version_code
    except Exception as e:
        print(f"[release_manager] Warning: Failed to run aapt dump badging ({e})")
        return None, None


def package_release(apk_input_path=None):
    """Packages APK, generates version.json, index.html, and validates consistency."""
    version_name, version_code = parse_pubspec_version()
    generate_version_info_dart(version_name, version_code)

    if apk_input_path is None:
        apk_input_path = DEFAULT_APK_PATH

    apk_input_path = Path(apk_input_path)
    if not apk_input_path.exists():
        raise FileNotFoundError(f"Input APK not found at {apk_input_path}")

    # Compute APK metadata
    sha256_hash, sha1_hash = compute_file_hashes(apk_input_path)
    file_size_bytes = apk_input_path.stat().st_size
    file_size_mb = f"{file_size_bytes / (1024 * 1024):.2f} MB"
    release_date_str = datetime.now().strftime("%d-%b-%Y")
    release_date_iso = datetime.now().strftime("%Y-%m-%d")

    apk_dir = apk_input_path.parent
    named_apk_name = f"ProValuer-v{version_name}-build-{version_code}.apk"
    named_apk_path = apk_dir / named_apk_name
    latest_apk_path = apk_dir / "latest.apk"

    # Copy to named APK and latest.apk
    shutil.copy2(apk_input_path, named_apk_path)
    shutil.copy2(apk_input_path, latest_apk_path)
    print(f"[release_manager] Generated named APK: {named_apk_name} ({file_size_mb})")
    print(f"[release_manager] Generated latest.apk alias")

    # Verify APK badging
    aapt_vname, aapt_vcode = extract_apk_badging(named_apk_path)
    if aapt_vname and aapt_vcode:
        if aapt_vname != version_name or aapt_vcode != version_code:
            raise ValueError(
                f"FAIL CONDITION: APK badging ({aapt_vname}+{aapt_vcode}) does not match pubspec ({version_name}+{version_code})!"
            )
        print(f"[release_manager] Verified APK Badging: versionName='{aapt_vname}', versionCode='{aapt_vcode}'")

    # Generate version.json
    version_manifest = {
        "versionName": version_name,
        "versionCode": version_code,
        "apkFileName": named_apk_name,
        "apkUrl": f"https://app.provaluer.in/download/{named_apk_name}",
        "forceUpdate": False,
        "releaseDate": release_date_iso,
        "fileSizeBytes": file_size_bytes,
        "fileSize": file_size_mb,
        "sha256": sha256_hash
    }

    DIST_DIR.mkdir(parents=True, exist_ok=True)
    dist_version_json = DIST_DIR / "version.json"
    dist_version_json.write_text(json.dumps(version_manifest, indent=2), encoding="utf-8")
    print(f"[release_manager] Generated {dist_version_json.relative_to(REPO_ROOT)}")

    # Generate landing page HTML from template
    if not TEMPLATE_HTML_PATH.exists():
        raise FileNotFoundError(f"Template not found at {TEMPLATE_HTML_PATH}")

    template_content = TEMPLATE_HTML_PATH.read_text(encoding="utf-8")
    rendered_html = (
        template_content
        .replace("{{VERSION_NAME}}", version_name)
        .replace("{{VERSION_CODE}}", str(version_code))
        .replace("{{APK_FILE_NAME}}", named_apk_name)
        .replace("{{APK_URL}}", f"/download/{named_apk_name}")
        .replace("{{RELEASE_DATE}}", release_date_str)
        .replace("{{FILE_SIZE}}", file_size_mb)
        .replace("{{SHA256}}", sha256_hash)
    )

    dist_index_html = DIST_DIR / "index.html"
    dist_index_html.write_text(rendered_html, encoding="utf-8")
    print(f"[release_manager] Generated {dist_index_html.relative_to(REPO_ROOT)}")

    # Comprehensive consistency check
    validate_release(version_name, version_code, sha256_hash, named_apk_path)

    return {
        "versionName": version_name,
        "versionCode": version_code,
        "apkFileName": named_apk_name,
        "namedApkPath": named_apk_path,
        "latestApkPath": latest_apk_path,
        "sha256": sha256_hash,
        "fileSize": file_size_mb,
        "fileSizeBytes": file_size_bytes,
        "versionJsonPath": dist_version_json,
        "indexHtmlPath": dist_index_html
    }


def validate_release(version_name, version_code, sha256_hash, named_apk_path):
    """Fails if any version inconsistency is detected across artifacts."""
    print("[release_manager] Running strict consistency validation...")

    # 1. Check version.json
    dist_version_json = DIST_DIR / "version.json"
    if not dist_version_json.exists():
        raise AssertionError("Validation failed: version.json does not exist!")
    vdata = json.loads(dist_version_json.read_text(encoding="utf-8"))
    if vdata["versionName"] != version_name or vdata["versionCode"] != version_code:
        raise AssertionError(f"FAIL: version.json ({vdata['versionName']}+{vdata['versionCode']}) != pubspec ({version_name}+{version_code})")

    # 2. Check index.html
    dist_index_html = DIST_DIR / "index.html"
    if not dist_index_html.exists():
        raise AssertionError("Validation failed: index.html does not exist!")
    hcontent = dist_index_html.read_text(encoding="utf-8")
    expected_pill = f"Version {version_name} (Build {version_code})"
    if expected_pill not in hcontent:
        raise AssertionError(f"FAIL: index.html missing '{expected_pill}'")
    if sha256_hash not in hcontent:
        raise AssertionError(f"FAIL: index.html missing SHA256 checksum '{sha256_hash}'")

    # 3. Check VersionInfo.dart
    if not VERSION_INFO_DART.exists():
        raise AssertionError("Validation failed: version_info.dart does not exist!")
    dcontent = VERSION_INFO_DART.read_text(encoding="utf-8")
    if f"'{version_name}'" not in dcontent or f"{version_code}" not in dcontent:
        raise AssertionError(f"FAIL: version_info.dart does not match {version_name}+{version_code}")

    print("[release_manager] ALL CONSISTENCY CHECKS PASSED (100% PARITY).")


def deploy_to_vps(vps_host=None, vps_user=None):
    """Deploys all release artifacts to production VPS."""
    if not vps_host:
        vps_host = os.environ.get("VPS_SSH_HOST", "66.116.241.171")
    if not vps_user:
        vps_user = os.environ.get("VPS_SSH_USER", "root")

    vps_host = vps_host.strip()
    vps_user = vps_user.strip()
    version_name, version_code = parse_pubspec_version()
    named_apk_name = f"ProValuer-v{version_name}-build-{version_code}.apk"
    named_apk_path = DEFAULT_APK_PATH.parent / named_apk_name
    latest_apk_path = DEFAULT_APK_PATH.parent / "latest.apk"
    version_json_path = DIST_DIR / "version.json"
    index_html_path = DIST_DIR / "index.html"

    print(f"[release_manager] Deploying release v{version_name} (Build {version_code}) to {vps_user}@{vps_host}...")

    # SSH options for reliable connection
    ssh_opts = ["-o", "StrictHostKeyChecking=no", "-o", "HostKeyAlgorithms=+ssh-rsa", "-o", "PubkeyAcceptedKeyTypes=+ssh-rsa"]

    # 1. Upload named APK
    print(f"-> Uploading {named_apk_name}...")
    subprocess.run(["scp"] + ssh_opts + [str(named_apk_path), f"{vps_user}@{vps_host}:/var/www/provaluer/downloads/{named_apk_name}"], check=True)

    # 2. Update symlink latest.apk -> named APK on VPS
    print(f"-> Updating symlink latest.apk -> {named_apk_name}...")
    remote_cmd = f"cd /var/www/provaluer/downloads && ln -sf {named_apk_name} latest.apk"
    subprocess.run(["ssh"] + ssh_opts + [f"{vps_user}@{vps_host}", remote_cmd], check=True)

    # 3. Upload version.json
    print(f"-> Uploading version.json...")
    subprocess.run(["scp"] + ssh_opts + [str(version_json_path), f"{vps_user}@{vps_host}:/var/www/provaluer/app/version.json"], check=True)

    # 4. Upload index.html
    print(f"-> Uploading index.html...")
    subprocess.run(["scp"] + ssh_opts + [str(index_html_path), f"{vps_user}@{vps_host}:/var/www/provaluer/downloads/index.html"], check=True)

    # 5. Remote validation
    print("-> Performing remote verification...")
    verify_cmd = f"aapt dump badging /var/www/provaluer/downloads/{named_apk_name} | grep -E 'package:'; sha256sum /var/www/provaluer/downloads/{named_apk_name}; ls -l /var/www/provaluer/downloads/latest.apk"
    res = subprocess.run(["ssh"] + ssh_opts + [f"{vps_user}@{vps_host}", verify_cmd], capture_output=True, text=True, check=True)
    print("=== REMOTE VPS VERIFICATION ===")
    print(res.stdout.strip())
    print("[release_manager] Deployment complete.")


if __name__ == "__main__":
    action = sys.argv[1] if len(sys.argv) > 1 else "package"
    if action == "prepare":
        vname, vcode = parse_pubspec_version()
        generate_version_info_dart(vname, vcode)
    elif action == "package":
        package_release()
    elif action == "deploy":
        package_release()
        deploy_to_vps()
    else:
        print(f"Usage: {sys.argv[0]} [prepare|package|deploy]")
        sys.exit(1)
